CREATE TABLE communities (
 id integer PRIMARY KEY CHECK (id > 0),
 name varchar(100) NOT NULL UNIQUE CHECK (length(name) > 0)
);
CREATE TABLE units (
 id integer PRIMARY KEY CHECK (id > 0),
 community_id integer NOT NULL REFERENCES communities(id),
 label varchar(20) NOT NULL CHECK (length(label) > 0),
 UNIQUE (community_id, label), UNIQUE (id, community_id)
);
CREATE TABLE app_users (id integer PRIMARY KEY CHECK (id > 0));
CREATE TABLE memberships (
 user_id integer NOT NULL REFERENCES app_users(id),
 community_id integer NOT NULL REFERENCES communities(id),
 role text NOT NULL CHECK (role IN ('resident','board_member','manager','admin')),
 unit_id integer,
 PRIMARY KEY (user_id, community_id),
 FOREIGN KEY (unit_id, community_id) REFERENCES units(id, community_id),
 CHECK (role <> 'resident' OR unit_id IS NOT NULL)
);
CREATE TABLE maintenance_requests (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 community_id integer NOT NULL REFERENCES communities(id),
 unit_id integer NOT NULL,
 submitted_by integer NOT NULL REFERENCES app_users(id),
 category text NOT NULL CHECK (length(category) > 0),
 description text NOT NULL CHECK (length(btrim(description)) > 0),
 status text NOT NULL CHECK (status IN ('Open','In progress','Resolved')),
 created_at timestamptz NOT NULL,
 FOREIGN KEY (unit_id, community_id) REFERENCES units(id, community_id),
 FOREIGN KEY (submitted_by, community_id) REFERENCES memberships(user_id, community_id)
);
CREATE INDEX requests_self_list ON maintenance_requests (community_id, submitted_by, created_at DESC, id DESC);
